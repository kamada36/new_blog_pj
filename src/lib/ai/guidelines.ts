/** カテゴリー選択の指示(構成案のcategorySlugに使う)。 */
export function buildCategorySection(categories: CategoryOption[]): string {
  if (categories.length === 0) return "";
  const list = categories
    .map((c) => `- ${c.slug}: 「${c.name}」${c.description ? ` … ${c.description}` : ""}`)
    .join("\n");
  return `
# 記事カテゴリー(categorySlugの選択肢)
この記事を掲載するカテゴリーを、次の slug の中から必ず1つだけ選び、categorySlug に出力してください(ここに無い値を作らないこと)。
${list}
`;
}

